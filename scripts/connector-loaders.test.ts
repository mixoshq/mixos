/**
 * The generated connector map (scripts/connector-loaders.ts), which the app
 * context, Verify connection and the webhook route construct connectors
 * through (src/lib/connectors/loader.ts).
 *
 * It replaced a template import that Turbopack resolved once, when the
 * importing module compiled, and that warned "Module not found" in every
 * checkout with no connectors. What holds the fix in place: every registered
 * connector with an index file gets one LITERAL import, under the key the
 * runtime looks up (src/lib/connectors/connector-modules.ts), and one without
 * an index file gets none, since a literal import of a missing file would fail
 * the build.
 *
 * No database and no generated registry: the generator scans a fixture
 * folder, and the map it writes is imported with `@connectors/` pointed there.
 */

import { after, describe, test, type TestContext } from "node:test";
import assert from "node:assert/strict";
import fs from "fs";
import { registerHooks } from "node:module";
import os from "os";
import path from "path";
import { pathToFileURL } from "url";
import { scanConnectors } from "./generate-project-registry";
import { connectorLoadersSource, loadableConnectors } from "./connector-loaders";
import { connectorLoaderKey } from "../src/lib/connectors/connector-modules";

const ROOT = path.resolve(__dirname, "..");
const tmp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "mixos-connector-loaders-")));
after(() => fs.rmSync(tmp, { recursive: true, force: true }));

/** The text between the map's braces, one line per loader. */
function entries(source: string): string[] {
  const body = source.slice(source.indexOf("= {") + 3, source.lastIndexOf("};"));
  return body.split("\n").filter((line) => line.trim() !== "");
}

/** The keys the generated map files its loaders under. */
function keys(source: string): string[] {
  return entries(source).map((line) => /^ {2}"([^"]+)":/.exec(line)?.[1] ?? line);
}

describe("the generated text", () => {
  const source = connectorLoadersSource(["acme-3f9a2c1b", "google-sheets-0a1b2c3d"]);

  test("one literal import per name, under the key the runtime looks up", () => {
    assert.deepEqual(entries(source), [
      `  "acme-3f9a2c1b/index": () => import("@connectors/acme-3f9a2c1b/index"),`,
      `  "google-sheets-0a1b2c3d/index": () => import("@connectors/google-sheets-0a1b2c3d/index"),`,
    ]);
    // The key is the runtime's own rule, so the two cannot drift.
    for (const name of ["acme-3f9a2c1b", "google-sheets-0a1b2c3d"]) {
      assert.ok(source.includes(`"${connectorLoaderKey(name)}"`));
    }
  });

  test("no template import, which is what this map exists to avoid", () => {
    assert.doesNotMatch(source, /import\(`/);
    assert.doesNotMatch(source, /\$\{/);
  });

  test("no connectors is an empty map, still exported under the name its consumer imports", () => {
    const empty = connectorLoadersSource([]);
    assert.deepEqual(entries(empty), []);
    assert.match(
      empty,
      /export const connectorLoaders: Record<string, \(\) => Promise<Record<string, unknown>>> = \{\n*\};\n$/,
    );
  });

  test("says it is server only, and who reads it, which imports it by that name", () => {
    assert.match(source, /^\/\/ AUTO-GENERATED by scripts\/generate-project-registry\.ts/);
    assert.match(source, /SERVER ONLY/);
    assert.ok(source.includes("src/lib/connectors/loader.ts"));
    const consumer = fs.readFileSync(path.join(ROOT, "src/lib/connectors/loader.ts"), "utf-8");
    assert.match(consumer, /import \{ connectorLoaders \} from "@\/generated\/connector-loaders";/);
  });
});

// ── from the generator's own scan ──────────────────────────────────────────

/** Each fixture connector, by folder, and the index file it has, if any. */
const CONNECTORS: Record<string, { file: string; text: string } | null> = {
  "alpha-3f9a2c1b": {
    file: "index.ts",
    text: `export default class Alpha {
  readonly from = "alpha";
}
`,
  },
  // A named class and no default export: the loader takes the first function.
  "beta-4e5f6a7b": {
    file: "index.tsx",
    text: `export class Beta {
  readonly from = "beta";
}
`,
  },
  // Registered, but with no index file: no loader, since a literal import of
  // a missing file would fail the build.
  "gamma-0a1b2c3d": null,
};

const TEMPLATE = path.join(ROOT, "connectors", "_template");

/** A fixture `connectors/` folder under `<tmp>/connectors-<n>/`. */
function writeConnectors(n: number): string {
  const dir = path.join(tmp, `connectors-${n}`);
  for (const [name, index] of Object.entries(CONNECTORS)) {
    const at = path.join(dir, name);
    fs.mkdirSync(path.join(at, "assets"), { recursive: true });
    // The template's manifest, named after this folder, as the scan requires.
    const manifest = JSON.parse(fs.readFileSync(path.join(TEMPLATE, "connector.json"), "utf-8"));
    fs.writeFileSync(
      path.join(at, "connector.json"),
      JSON.stringify({ ...manifest, registryId: name, displayName: name }),
    );
    fs.copyFileSync(path.join(TEMPLATE, "assets", "icon.svg"), path.join(at, "assets", "icon.svg"));
    if (index) fs.writeFileSync(path.join(at, index.file), index.text);
  }
  return dir;
}

async function scan(t: TestContext, dir: string) {
  t.mock.method(console, "log", () => {});
  t.mock.method(console, "warn", () => {});
  const connectors = await scanConnectors(dir, { emit: false });
  assert.deepEqual(
    connectors.map((c) => c.name).sort(),
    Object.keys(CONNECTORS).sort(),
    "every fixture connector is registered, the one without an index file included",
  );
  return connectors;
}

describe("the map the generator writes", () => {
  test("holds the registered connectors with an index file, .ts or .tsx, and not the one without", async (t) => {
    const dir = writeConnectors(0);
    const connectors = await scan(t, dir);
    assert.deepEqual(
      keys(connectorLoadersSource(loadableConnectors(dir, connectors))).sort(),
      ["alpha-3f9a2c1b", "beta-4e5f6a7b"].map(connectorLoaderKey).sort(),
    );
  });

  test("loads each connector's own module once imported, .tsx included", async (t) => {
    const dir = writeConnectors(1);
    const connectors = await scan(t, dir);
    const generated = path.join(tmp, "generated-1");
    fs.mkdirSync(generated, { recursive: true });
    const file = path.join(generated, "connector-loaders.ts");
    fs.writeFileSync(file, connectorLoadersSource(loadableConnectors(dir, connectors)));

    // `@connectors/` → the fixture folder, as the bundler's alias points it at
    // connectors/. The specifier has no extension, as in the bundle, so find
    // the one on disk.
    const resolver = registerHooks({
      resolve(specifier, context, nextResolve) {
        if (specifier.startsWith("@connectors/")) {
          const base = path.join(dir, specifier.slice("@connectors/".length));
          const found = [".ts", ".tsx"].map((ext) => base + ext).find((f) => fs.existsSync(f));
          return nextResolve(pathToFileURL(found ?? `${base}.ts`).href, context);
        }
        return nextResolve(specifier, context);
      },
    });
    t.after(() => resolver.deregister());

    const { connectorLoaders } = (await import(pathToFileURL(file).href)) as {
      connectorLoaders: Record<string, () => Promise<Record<string, unknown>>>;
    };
    const alpha = await connectorLoaders[connectorLoaderKey("alpha-3f9a2c1b")]();
    assert.equal(new (alpha.default as new () => { from: string })().from, "alpha");
    const beta = await connectorLoaders[connectorLoaderKey("beta-4e5f6a7b")]();
    assert.equal(new (beta.Beta as new () => { from: string })().from, "beta");
    assert.equal(Object.hasOwn(connectorLoaders, connectorLoaderKey("gamma-0a1b2c3d")), false);
  });
});

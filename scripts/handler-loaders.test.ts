/**
 * The generated handler maps (scripts/handler-loaders.ts), which the MCP
 * server, the scheduler and the services broker load app code through.
 *
 * They replaced template imports that Turbopack resolved once, when the
 * importing module compiled, so a tool, sync, job or service added under
 * `next dev` did not load until a restart. What holds the fix in place: every
 * handler gets one LITERAL import, under the key the runtime looks up
 * (src/lib/apps/handler-modules.ts), in its own kind's map, and each map
 * covers the handlers the generator registers, no more and no fewer.
 *
 * No database and no generated registry: the generator scans a fixture
 * folder, and the maps it writes are imported with `@apps/` pointed there.
 */

import { after, describe, test, type TestContext } from "node:test";
import assert from "node:assert/strict";
import fs from "fs";
import { registerHooks } from "node:module";
import os from "os";
import path from "path";
import { pathToFileURL } from "url";
import { scanApps } from "./generate-project-registry";
import { HANDLER_KINDS, HANDLER_MAPS, handlerLoadersSource } from "./handler-loaders";
import { handlerLoaderKey, type HandlerKind } from "../src/lib/apps/handler-modules";

const ROOT = path.resolve(__dirname, "..");
const tmp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "mixos-handler-loaders-")));
// A fixture tool imports `zod`, which Node finds by walking up from the file.
// The link goes before the folder does, so removing the folder never follows it.
fs.symlinkSync(path.join(ROOT, "node_modules"), path.join(tmp, "node_modules"), "dir");
after(() => {
  fs.unlinkSync(path.join(tmp, "node_modules"));
  fs.rmSync(tmp, { recursive: true, force: true });
});

/** The text between the map's braces, one line per loader. */
function entries(source: string): string[] {
  const body = source.slice(source.indexOf("= {") + 3, source.lastIndexOf("};"));
  return body.split("\n").filter((line) => line.trim() !== "");
}

/** The keys a generated map files its loaders under. */
function keys(source: string): string[] {
  return entries(source).map((line) => /^ {2}"([^"]+)":/.exec(line)?.[1] ?? line);
}

describe("the generated text", () => {
  const apps = [
    {
      slug: "acme-3f9a2c1b",
      mcp: [{ name: "pipeline" }, { name: "deal-notes" }],
      sync: [{ name: "deals" }],
      schedules: [{ name: "nightly" }, { name: "hourly-digest" }],
      provides: [{ name: "accounts" }],
    },
    { slug: "quiet-0a1b2c3d", mcp: [], sync: [], schedules: [], provides: [] },
    { slug: "bare-4e5f6a7b" },
  ];

  const expected: Record<HandlerKind, string[]> = {
    mcp: ["pipeline", "deal-notes"],
    sync: ["deals"],
    jobs: ["nightly", "hourly-digest"],
    services: ["accounts"],
  };

  for (const kind of HANDLER_KINDS) {
    describe(`${kind}: ${HANDLER_MAPS[kind].file}`, () => {
      const source = handlerLoadersSource(kind, apps);

      test("one literal import per declared name, under the key the runtime looks up", () => {
        assert.deepEqual(
          entries(source),
          expected[kind].map(
            (name) =>
              `  "acme-3f9a2c1b/${kind}/${name}": () => import("@apps/acme-3f9a2c1b/${kind}/${name}"),`,
          ),
        );
        // The key is the runtime's own rule, so the two cannot drift.
        for (const name of expected[kind]) {
          assert.ok(source.includes(`"${handlerLoaderKey("acme-3f9a2c1b", kind, name)}"`));
        }
      });

      test("no template import, which is the bug this map exists to avoid", () => {
        assert.doesNotMatch(source, /import\(`/);
        assert.doesNotMatch(source, /\$\{/);
      });

      test("only its own kind, and nothing for an app without one", () => {
        for (const other of HANDLER_KINDS.filter((k) => k !== kind)) {
          for (const name of expected[other]) {
            assert.doesNotMatch(source, new RegExp(`/${other}/${name}"`));
          }
        }
        assert.doesNotMatch(source, /quiet-0a1b2c3d|bare-4e5f6a7b/);
      });

      test("no apps is an empty map, still exported under the name its consumer imports", () => {
        const empty = handlerLoadersSource(kind, []);
        assert.deepEqual(entries(empty), []);
        assert.match(
          empty,
          new RegExp(
            `export const ${HANDLER_MAPS[kind].exportName}: Record<string, \\(\\) => Promise<Record<string, unknown>>> = \\{\\n*\\};\\n$`,
          ),
        );
      });

      test("says it is server only, and who reads it", () => {
        assert.match(source, /^\/\/ AUTO-GENERATED by scripts\/generate-project-registry\.ts/);
        assert.match(source, /SERVER ONLY/);
        assert.ok(source.includes(HANDLER_MAPS[kind].consumer.replace(/\.ts$/, "")));
      });
    });
  }

  test("each kind has its own file and export, and each consumer imports its map by that name", () => {
    const files = HANDLER_KINDS.map((k) => HANDLER_MAPS[k].file);
    const exports = HANDLER_KINDS.map((k) => HANDLER_MAPS[k].exportName);
    assert.equal(new Set(files).size, files.length);
    assert.equal(new Set(exports).size, exports.length);
    for (const kind of HANDLER_KINDS) {
      const { file, exportName, consumer } = HANDLER_MAPS[kind];
      const text = fs.readFileSync(path.join(ROOT, consumer), "utf-8");
      const from = `@/generated/${file.replace(/\.ts$/, "")}`;
      assert.match(
        text,
        new RegExp(`import \\{ ${exportName} \\} from "${from.replace(/[/.]/g, "\\$&")}";`),
        `${consumer} does not import ${exportName} from ${from}`,
      );
    }
  });
});

// ── from the generator's own scan ──────────────────────────────────────────

const SLUG = "probe-3f9a2c1b";

/** Each handler file, by its path under the app, and what its module exports. */
const HANDLERS: Record<string, string> = {
  "mcp/peek.ts": `import { z } from "zod";

export const inputSchema = z.object({});

export default async function peek() {
  return { from: "mcp/peek" };
}
`,
  "mcp/count-items.ts": `import { z } from "zod";

export const inputSchema = z.object({ limit: z.number().optional() });

export default async function countItems() {
  return { from: "mcp/count-items" };
}
`,
  // A sync's default export is a defineSync() result; the map only loads it.
  "sync/feed.ts": `export default { from: "sync/feed" };
`,
  "jobs/tick.ts": `export default async function tick() {
  return "jobs/tick";
}
`,
  "jobs/nightly-digest.tsx": `export default async function nightlyDigest() {
  return "jobs/nightly-digest";
}
`,
  "services/lookup.ts": `export default async function lookup() {
  return { from: "services/lookup" };
}
`,
};

const MANIFEST = {
  $schema: "https://mixos.org/schemas/app/v1.json",
  registryId: SLUG,
  name: "Probe",
  // A sync keeps its watermark in the app's own schema.
  database: true,
  mcp: [
    { name: "peek", description: "Peeks.", sources: ["mixos"] },
    { name: "count-items", description: "Counts.", sources: ["mixos"] },
  ],
  sync: [
    {
      name: "feed",
      schedule: { everyMinutes: 15 },
      source: "mixos",
      window: { coldStartDays: 7, defaultDays: 1, minDays: 1 },
      budgetMs: 10000,
    },
  ],
  schedules: [
    { name: "tick", everyMinutes: 5 },
    { name: "nightly-digest", cron: "0 3 * * *" },
  ],
  provides: [{ name: "lookup", consumers: "*" }],
};

/** What each kind's map should hold for the fixture, by name. */
const DECLARED: Record<HandlerKind, string[]> = {
  mcp: ["peek", "count-items"],
  sync: ["feed"],
  jobs: ["tick", "nightly-digest"],
  services: ["lookup"],
};

/** A fixture app under `<tmp>/apps-<n>/`, its handlers written out. */
function writeApp(n: number): string {
  const apps = path.join(tmp, `apps-${n}`);
  const dir = path.join(apps, SLUG);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "app.json"), JSON.stringify(MANIFEST));
  for (const [file, text] of Object.entries(HANDLERS)) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.writeFileSync(path.join(dir, file), text);
  }
  // On disk but not declared: a file in a handler folder is not a handler.
  fs.writeFileSync(path.join(dir, "jobs", "helpers.ts"), "export const x = 1;\n");
  return apps;
}

async function scan(t: TestContext, apps: string) {
  t.mock.method(console, "log", () => {});
  const warnings: string[] = [];
  t.mock.method(console, "warn", (line: unknown) => warnings.push(String(line)));
  const manifests = await scanApps(apps, { emit: false });
  assert.ok(
    manifests.some((m) => m.slug === SLUG),
    `the fixture was not registered:\n${warnings.join("\n")}`,
  );
  return manifests;
}

describe("the maps the generator writes", () => {
  test("hold exactly the declared handlers, each in its own kind's map", async (t) => {
    const manifests = await scan(t, writeApp(0));
    for (const kind of HANDLER_KINDS) {
      assert.deepEqual(
        keys(handlerLoadersSource(kind, manifests)).sort(),
        DECLARED[kind].map((name) => handlerLoaderKey(SLUG, kind, name)).sort(),
        kind,
      );
    }
  });

  test("load each handler's own module once imported, .tsx included", async (t) => {
    const apps = writeApp(1);
    const manifests = await scan(t, apps);
    const generated = path.join(tmp, "generated-1");
    fs.mkdirSync(generated, { recursive: true });
    for (const kind of HANDLER_KINDS) {
      fs.writeFileSync(path.join(generated, HANDLER_MAPS[kind].file), handlerLoadersSource(kind, manifests));
    }

    // `@apps/` → the fixture folder, as the bundler's alias points it at apps/.
    // The specifier has no extension, as in the bundle, so find the one on disk.
    const resolver = registerHooks({
      resolve(specifier, context, nextResolve) {
        if (specifier.startsWith("@apps/")) {
          const base = path.join(apps, specifier.slice("@apps/".length));
          const file = [".ts", ".tsx"].map((ext) => base + ext).find((f) => fs.existsSync(f));
          return nextResolve(pathToFileURL(file ?? `${base}.ts`).href, context);
        }
        return nextResolve(specifier, context);
      },
    });
    t.after(() => resolver.deregister());

    for (const kind of HANDLER_KINDS) {
      const { exportName, file } = HANDLER_MAPS[kind];
      const mod = (await import(pathToFileURL(path.join(generated, file)).href)) as Record<
        string,
        Record<string, () => Promise<Record<string, unknown>>>
      >;
      const loaders = mod[exportName];
      assert.ok(loaders, `${file} does not export ${exportName}`);
      for (const name of DECLARED[kind]) {
        const handler = await loaders[handlerLoaderKey(SLUG, kind, name)]();
        const out =
          typeof handler.default === "function"
            ? await (handler.default as () => Promise<unknown>)()
            : handler.default;
        const from = typeof out === "string" ? out : (out as { from: string }).from;
        assert.equal(from, `${kind}/${name}`);
      }
    }
  });
});

/**
 * Renders docs/themes/tokens.md from the token contract.
 *
 * The contract is code (src/lib/themes/tokens.ts) because the generator and the
 * lint rule both enforce it. A hand-written table beside it would drift the
 * first time a token was added — and a token reference that is wrong is worse
 * than none, because an author trusts it. So the doc is generated.
 *
 * Run: npx tsx scripts/generate-token-docs.ts
 */
import fs from "fs";
import path from "path";
import {
  REQUIRED_TOKENS,
  OPTIONAL_TOKENS,
  FORBIDDEN_TOKENS,
  CONTRAST_PAIRS,
  RATIO_FOR,
  SURFACE_ALLOWLIST,
} from "../src/lib/themes/tokens";

const row = (t: { name: string; kind: string; role: string }) =>
  `| \`--${t.name}\` | ${t.kind} | ${t.role} |`;

const out = `<!-- GENERATED by scripts/generate-token-docs.ts — do not edit by hand.
     The contract is src/lib/themes/tokens.ts; regenerate after changing it. -->

# Token reference

Every token a theme may set, and what reads it. The authoritative source is
[\`src/lib/themes/tokens.ts\`](../../src/lib/themes/tokens.ts) — this page is
generated from it, so the two cannot disagree.

## Required

A theme must define all of these in \`:root\`, which is the only block a theme
declares tokens in — a theme is a single palette, and a dark look is a separate
theme rather than a second block. A missing token is a build error: an undefined
custom property renders as \`unset\`, which is a transparent surface or invisible
text, not a sensible default.

| Token | Kind | Role |
| --- | --- | --- |
${REQUIRED_TOKENS.map(row).join("\n")}

## Optional

${OPTIONAL_TOKENS.map(row).join("\n") ? `| Token | Kind | Role |
| --- | --- | --- |
${OPTIONAL_TOKENS.map(row).join("\n")}` : "_None._"}

## Never

${
  FORBIDDEN_TOKENS.length > 0
    ? `${FORBIDDEN_TOKENS.map((t) => `- \`--${t}\``).join("\n")}

A theme declaring one of these fails the build.`
    : `_None. Every colour the UI renders comes from the active theme, in every
environment._

The check is kept rather than deleted: it is the hook for any future value that
must survive a theme change. It held the localhost menu-bar band until that
treatment was dropped in favour of one consistent look.`
}

## Verified pairs

Computed once per theme, over its one palette. See [contrast.md](contrast.md) for what
to do when one fails.

| Pair | Floor | Why |
| --- | --- | --- |
${CONTRAST_PAIRS.map(
  (p) => `| \`--${p.fg}\` on \`--${p.bg}\` | ${RATIO_FOR[p.kind]}:1 | ${p.why} |`,
).join("\n")}

## Styleable surfaces

Beyond tokens, a theme may style these classes, their states, and combinations
between them — nothing else.

${SURFACE_ALLOWLIST.map((s) => `- \`${s}\``).join("\n")}
`;

const file = path.resolve(__dirname, "../docs/themes/tokens.md");
fs.writeFileSync(file, out, "utf-8");
console.log(`Wrote ${path.relative(process.cwd(), file)}`);

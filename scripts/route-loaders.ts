/**
 * The text of src/generated/app-route-loaders.ts: one explicit `import()` per
 * route of every registered app.
 *
 * WHY EXPLICIT. The gateway and `callAppRoute` used to load a route with a
 * template import, `import(\`@apps/${slug}/api/${path}/route\`)`. Turbopack
 * turns that into a context of the files it matches when the importing module
 * compiles, and nothing recompiles the gateway when an app is added — so under
 * `next dev`, a new app's pages worked (their loaders are generated, see
 * `pageLoaders`) and every one of its routes was a 404 until a restart. A
 * generated file of literal imports is rewritten by `npm run registry`, Next
 * recompiles it, and the new routes are in the graph.
 *
 * Built from the hoisted `routes` of the apps the scan accepted, so the map
 * holds exactly the routes the registry vouches for: a rejected app gets no
 * loaders, as it gets no registry entry.
 */

import { routeLoaderKey, routeModulePath } from "../src/lib/apps/route-modules";

export interface RouteLoaderApp {
  slug: string;
  routes?: readonly { path: string }[];
}

export function routeLoadersSource(apps: readonly RouteLoaderApp[]): string {
  const entries = apps.flatMap((app) =>
    (app.routes ?? []).map((route) => {
      const modulePath = routeModulePath(route.path);
      const key = routeLoaderKey(app.slug, modulePath);
      return `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`@apps/${key}`)}),`;
    }),
  );

  return `// AUTO-GENERATED by scripts/generate-project-registry.ts — do not edit
//
// SERVER ONLY. Every registered app's API routes, one explicit import each, so
// a route added while \`next dev\` runs is in the module graph as soon as
// \`npm run registry\` rewrites this file (scripts/route-loaders.ts says why a
// template import was not enough). A route module may reach the database or a
// connector, so this map must never enter the client graph. Its single
// consumer is src/lib/apps/route-loader.ts.

export const routeLoaders: Record<string, () => Promise<Record<string, unknown>>> = {
${entries.join("\n")}
};
`;
}

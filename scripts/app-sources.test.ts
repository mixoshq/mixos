/**
 * The generated Tailwind sources (scripts/app-sources.ts), which make the
 * classes a registered app uses get generated even where git ignores the app.
 *
 * Tailwind skips git-ignored files, and a clone of the core repo ignores the
 * apps it doesn't carry (scripts/core-excludes.ts). The end-to-end test builds
 * that situation in a throwaway git repository and runs the real Tailwind
 * PostCSS plugin over it, once without the generated file and once with it.
 * Each run is a child process: the plugin caches its result per input file,
 * and a second run in the same process can answer from the first.
 */

import { after, describe, test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { appSourcesCss } from "./app-sources";

const ROOT = path.resolve(__dirname, "..");

describe("the generated text", () => {
  test("one @source per app, in order, relative to src/generated/", () => {
    const css = appSourcesCss(["tasks-3f9a2c1b", "wall-e-345e113c"]);
    const sources = css.split("\n").filter((l) => l.startsWith("@source"));
    assert.deepEqual(sources, [
      '@source "../../apps/tasks-3f9a2c1b";',
      '@source "../../apps/wall-e-345e113c";',
    ]);
    // From src/generated/, the path lands on the app's folder.
    const from = path.join(ROOT, "src", "generated");
    assert.equal(path.resolve(from, "../../apps/tasks-3f9a2c1b"), path.join(ROOT, "apps", "tasks-3f9a2c1b"));
  });

  test("says it is generated, and why, and no apps is the header alone", () => {
    const empty = appSourcesCss([]);
    assert.match(empty, /^\/\* AUTO-GENERATED by scripts\/generate-project-registry\.ts/);
    assert.match(empty, /git ignores/);
    assert.doesNotMatch(empty, /@source/);
    assert.ok(empty.trimEnd().endsWith("*/"));
  });

  test("globals.css imports it", () => {
    const globals = fs.readFileSync(path.join(ROOT, "src", "app", "globals.css"), "utf8");
    assert.match(globals, /^@import "\.\.\/generated\/app-sources\.css";$/m);
  });
});

describe("through Tailwind, in a repository that ignores its apps", () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "mixos-app-sources-"));
  after(() => fs.rmSync(work, { recursive: true, force: true }));

  // A class no file outside the fixture app uses, so only the app can have produced it.
  const CLASS = "grid-cols-11";

  /** A throwaway repository laid out like a core clone, ignoring `/apps/*`. */
  function repo(name: string, withSources: boolean): string | null {
    const dir = path.join(work, name);
    fs.mkdirSync(path.join(dir, "apps", "probe-0a1b2c3d", "widgets"), { recursive: true });
    fs.mkdirSync(path.join(dir, "src", "generated"), { recursive: true });
    fs.mkdirSync(path.join(dir, "src", "app"), { recursive: true });
    if (spawnSync("git", ["init", "-q"], { cwd: dir }).status !== 0) return null;
    // Not every git's template makes info/.
    fs.mkdirSync(path.join(dir, ".git", "info"), { recursive: true });
    fs.appendFileSync(path.join(dir, ".git", "info", "exclude"), "/apps/*\n");
    fs.writeFileSync(path.join(dir, ".gitignore"), "node_modules\n");
    fs.symlinkSync(path.join(ROOT, "node_modules"), path.join(dir, "node_modules"), "dir");
    fs.writeFileSync(
      path.join(dir, "apps", "probe-0a1b2c3d", "widgets", "days.tsx"),
      `export default function Days() {\n  return <div className="${CLASS}" />;\n}\n`,
    );
    fs.writeFileSync(path.join(dir, "src", "generated", "app-sources.css"), appSourcesCss(["probe-0a1b2c3d"]));
    fs.writeFileSync(
      path.join(dir, "src", "app", "globals.css"),
      `@import "tailwindcss";\n${withSources ? '@import "../generated/app-sources.css";\n' : ""}`,
    );
    return dir;
  }

  /** Whether Tailwind, run over the repository's globals.css in a fresh process, generated CLASS. */
  function generates(dir: string): boolean {
    const probe = `
      import fs from "node:fs";
      import { createRequire } from "node:module";
      const require = createRequire(${JSON.stringify(path.join(ROOT, "package.json"))});
      const postcss = (await import(require.resolve("postcss"))).default;
      const tailwind = (await import(require.resolve("@tailwindcss/postcss"))).default;
      const from = ${JSON.stringify(path.join(dir, "src", "app", "globals.css"))};
      const result = await postcss([tailwind()]).process(fs.readFileSync(from, "utf8"), { from });
      process.stdout.write(result.css.includes(${JSON.stringify(`.${CLASS}`)}) ? "yes" : "no");
    `;
    const run = spawnSync(process.execPath, ["--input-type=module", "-e", probe], { cwd: dir, encoding: "utf8" });
    assert.equal(run.status, 0, run.stderr);
    return run.stdout.trim() === "yes";
  }

  test("git ignores the app, as a core clone's .git/info/exclude does", (t) => {
    const dir = repo("check", false);
    if (!dir) return t.skip("git isn't available");
    const check = spawnSync("git", ["check-ignore", "-q", "apps/probe-0a1b2c3d/widgets/days.tsx"], { cwd: dir });
    assert.equal(check.status, 0, "the fixture app should be git-ignored");
  });

  test("without the generated sources, the app's class is not generated", (t) => {
    const dir = repo("without", false);
    if (!dir) return t.skip("git isn't available");
    assert.equal(generates(dir), false);
  });

  test("with them imported, as globals.css does, it is", (t) => {
    const dir = repo("with", true);
    if (!dir) return t.skip("git isn't available");
    assert.equal(generates(dir), true);
  });
});

/**
 * The generated route loader map (scripts/route-loaders.ts), which the gateway
 * and callAppRoute load app routes through.
 *
 * It replaced a template import that Turbopack resolved once, when the gateway
 * compiled, so a route added under `next dev` was a 404 until a restart. What
 * holds the fix in place: every route gets one LITERAL import, under the key
 * the runtime looks up (src/lib/apps/route-modules.ts), and the map covers
 * every route file the generator registers, no more and no fewer.
 *
 * No database and no generated registry: the generator scans a fixture
 * folder, and the map it writes is imported with `@apps/` pointed there.
 */

import { after, describe, test, type TestContext } from "node:test";
import assert from "node:assert/strict";
import fs from "fs";
import { registerHooks } from "node:module";
import os from "os";
import path from "path";
import { pathToFileURL } from "url";
import { scanApps } from "./generate-project-registry";
import { routeLoadersSource } from "./route-loaders";
import { routeLoaderKey } from "../src/lib/apps/route-modules";
import { isRouteDefinition, type RouteDefinition } from "../src/lib/apps/route";

const ROOT = path.resolve(__dirname, "..");
const tmp = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "mixos-route-loaders-")));
// The generator imports each fixture route, and a route imports `zod`, which
// Node finds by walking up from the file. The link goes before the folder
// does, so removing the folder never follows it.
fs.symlinkSync(path.join(ROOT, "node_modules"), path.join(tmp, "node_modules"), "dir");
after(() => {
  fs.unlinkSync(path.join(tmp, "node_modules"));
  fs.rmSync(tmp, { recursive: true, force: true });
});

/** The text between the map's braces, one line per loader. */
function entries(source: string): string[] {
  const body = source.slice(source.indexOf("= {") + 3, source.lastIndexOf("};"));
  return body.split("\n").filter((line) => line.trim() !== "");
}

describe("the generated text", () => {
  const source = routeLoadersSource([
    {
      slug: "acme-3f9a2c1b",
      routes: [{ path: "" }, { path: "items" }, { path: "items/[id]" }, { path: "files/[...rest]" }],
    },
    { slug: "quiet-0a1b2c3d", routes: [] },
    { slug: "bare-4e5f6a7b" },
  ]);

  test("one literal import per route, under the key the runtime looks up", () => {
    assert.deepEqual(entries(source), [
      `  "acme-3f9a2c1b/api/index/route": () => import("@apps/acme-3f9a2c1b/api/index/route"),`,
      `  "acme-3f9a2c1b/api/items/route": () => import("@apps/acme-3f9a2c1b/api/items/route"),`,
      `  "acme-3f9a2c1b/api/items/[id]/route": () => import("@apps/acme-3f9a2c1b/api/items/[id]/route"),`,
      `  "acme-3f9a2c1b/api/files/[...rest]/route": () => import("@apps/acme-3f9a2c1b/api/files/[...rest]/route"),`,
    ]);
    // The key is the runtime's own rule, so the two cannot drift.
    assert.ok(source.includes(`"${routeLoaderKey("acme-3f9a2c1b", "items/[id]")}"`));
  });

  test("no template import, which is the bug this map exists to avoid", () => {
    assert.doesNotMatch(source, /import\(`/);
    assert.doesNotMatch(source, /\$\{/);
  });

  test("an app without routes adds nothing", () => {
    assert.doesNotMatch(source, /quiet-0a1b2c3d|bare-4e5f6a7b/);
  });

  test("no apps is an empty map, still exported", () => {
    const empty = routeLoadersSource([]);
    assert.deepEqual(entries(empty), []);
    assert.match(empty, /export const routeLoaders: Record<string, \(\) => Promise<Record<string, unknown>>> = \{\n*\};\n$/);
  });

  test("says it is server only, and who reads it", () => {
    assert.match(source, /^\/\/ AUTO-GENERATED by scripts\/generate-project-registry\.ts/);
    assert.match(source, /SERVER ONLY/);
    assert.match(source, /src\/lib\/apps\/route-loader\.ts/);
  });
});

// ── from the generator's own scan ──────────────────────────────────────────

const SLUG = "probe-3f9a2c1b";

/** Each route, by its path under `api/`, answering with that path. */
const ROUTES = ["index", "items", "items/[id]", "files/[...rest]", "deep/er/still"];

function routeFile(name: string): string {
  return `import { z } from "zod";
import { defineRoute } from "@/lib/apps/route";

export const GET = defineRoute({
  auth: ["session"],
  output: z.object({ route: z.string() }),
  handler: async () => ({ route: ${JSON.stringify(name)} }),
});
`;
}

/** A fixture app under `<tmp>/apps-<n>/`, its routes written out. */
function writeApp(n: number): string {
  const apps = path.join(tmp, `apps-${n}`);
  const dir = path.join(apps, SLUG);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "app.json"),
    JSON.stringify({ $schema: "https://mixos.org/schemas/app/v1.json", registryId: SLUG, name: "Probe" }),
  );
  for (const name of ROUTES) {
    fs.mkdirSync(path.join(dir, "api", name), { recursive: true });
    fs.writeFileSync(path.join(dir, "api", name, "route.ts"), routeFile(name));
  }
  // Not a route: the walk lists `route.ts` only.
  fs.writeFileSync(path.join(dir, "api", "items", "helpers.ts"), "export const x = 1;\n");
  return apps;
}

async function scan(t: TestContext, apps: string) {
  t.mock.method(console, "log", () => {});
  const warnings: string[] = [];
  t.mock.method(console, "warn", (line: unknown) => warnings.push(String(line)));
  const manifests = await scanApps(apps, { emit: false });
  assert.ok(
    manifests.some((m) => m.slug === SLUG),
    `the fixture was not registered:\n${warnings.join("\n")}`,
  );
  return manifests;
}

describe("the map the generator writes", () => {
  test("has exactly one entry per route file on disk", async (t) => {
    const apps = writeApp(0);
    const source = routeLoadersSource(await scan(t, apps));
    const keys = entries(source).map((line) => /^ {2}"([^"]+)":/.exec(line)?.[1]);
    assert.deepEqual(
      keys.sort(),
      ROUTES.map((name) => routeLoaderKey(SLUG, name)).sort(),
    );
  });

  test("loads each route's own module once imported", async (t) => {
    const apps = writeApp(1);
    const generated = path.join(tmp, "generated-1", "app-route-loaders.ts");
    fs.mkdirSync(path.dirname(generated), { recursive: true });
    fs.writeFileSync(generated, routeLoadersSource(await scan(t, apps)));

    // `@apps/` → the fixture folder, as the bundler's alias points it at apps/.
    const resolver = registerHooks({
      resolve(specifier, context, nextResolve) {
        if (specifier.startsWith("@apps/")) {
          const file = path.join(apps, `${specifier.slice("@apps/".length)}.ts`);
          return nextResolve(pathToFileURL(file).href, context);
        }
        return nextResolve(specifier, context);
      },
    });
    t.after(() => resolver.deregister());

    const { routeLoaders } = (await import(pathToFileURL(generated).href)) as {
      routeLoaders: Record<string, () => Promise<Record<string, unknown>>>;
    };
    for (const name of ROUTES) {
      const mod = await routeLoaders[routeLoaderKey(SLUG, name)]();
      assert.ok(isRouteDefinition(mod.GET), `${name}: GET is not a defineRoute() result`);
      // The fixture's handler reads neither its context nor its input.
      const out = await (mod.GET as RouteDefinition).handler(
        {} as never,
        {} as never,
        new Request("http://mixos.test/"),
      );
      assert.deepEqual(out, { route: name });
    }
  });
});

/**
 * The text of src/generated/connector-loaders.ts: one explicit `import()` per
 * registered connector's `index`.
 *
 * WHY EXPLICIT. The app context, Verify connection and the webhook route used
 * to load a connector with a template import,
 * `import(\`@connectors/${name}/index\`)`. Turbopack turns that into a context
 * of the files it matches when the importing module compiles, and doesn't
 * always resolve it again when a connector is added under `next dev`: the
 * gateway's template for app routes wasn't (./route-loaders.ts). A generated
 * file of literal imports is rewritten by `npm run registry`, Next recompiles
 * it, and the new connector is in the graph. With no connector, the template
 * also matched nothing, and Turbopack warned "Module not found" on every
 * compile; an empty map warns about nothing.
 *
 * ONLY CONNECTORS WITH AN INDEX FILE. The scan doesn't require one, and a
 * literal import of a file that isn't there fails the build, where the
 * template only failed when it ran. So the map lists the registered
 * connectors that have one (`loadableConnectors`, CONNECTOR_INDEX_FILES); any
 * other is missing from the map and fails to load, as it did before.
 *
 * One map for every connector, as the template's context was: each of its
 * three callers can be handed any of them.
 */

import fs from "fs";
import path from "path";
import {
  CONNECTOR_INDEX_FILES,
  connectorLoaderKey,
} from "../src/lib/connectors/connector-modules";

/** The registered connectors with an index file in their folder under `connectorsDir`, in order. */
export function loadableConnectors(
  connectorsDir: string,
  connectors: readonly { name: string }[],
): string[] {
  return connectors
    .map((c) => c.name)
    .filter((name) =>
      CONNECTOR_INDEX_FILES.some((file) => fs.existsSync(path.join(connectorsDir, name, file))),
    );
}

/** The generated file's text, for the connectors `loadableConnectors` chose. Pure. */
export function connectorLoadersSource(names: readonly string[]): string {
  const entries = names.map((name) => {
    const key = connectorLoaderKey(name);
    return `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`@connectors/${key}`)}),`;
  });

  return `// AUTO-GENERATED by scripts/generate-project-registry.ts — do not edit
//
// SERVER ONLY. Every registered connector's index module, one explicit import
// each, so a connector added while \`next dev\` runs is in the module graph as
// soon as \`npm run registry\` rewrites this file (scripts/connector-loaders.ts
// says why this is not a template import). A connector holds credentials and
// talks to the outside world, so this map must never enter the client graph.
// Its single consumer is src/lib/connectors/loader.ts.

export const connectorLoaders: Record<string, () => Promise<Record<string, unknown>>> = {
${entries.join("\n")}
};
`;
}

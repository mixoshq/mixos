/**
 * The text of src/generated/app-sources.css: one Tailwind `@source` per
 * registered app's folder, which src/app/globals.css imports.
 *
 * WHY. Tailwind v4 finds the classes to generate by scanning the project, and
 * skips what git ignores. In a clone of the core repository,
 * ./core-excludes.ts ignores `/apps/*` in `.git/info/exclude`, so a class only
 * a non-core app uses was never generated there, and the app rendered without
 * it. Registering `apps/` as a source doesn't help: the rule matches each
 * app's folder as the scanner walks `apps/`. Registering an app's folder by
 * name does, because nothing inside it is ignored in its own right. See
 * docs/plans/20261122_1152-app-tailwind-sources.md.
 *
 * EVERY REGISTERED APP. For an app git doesn't ignore, its line repeats what
 * automatic detection finds anyway. Listing all of them keeps this free of
 * git, so the file is the same in a core clone, a fork, CI and a Docker build.
 * An app the scan rejected isn't served, so it isn't listed.
 */

/** Paths are relative to the generated file, src/generated/. */
const APPS_FROM_GENERATED = "../../apps";

export function appSourcesCss(slugs: readonly string[]): string {
  const lines = slugs.map((slug) => `@source ${JSON.stringify(`${APPS_FROM_GENERATED}/${slug}`)};`);
  return `/* AUTO-GENERATED by scripts/generate-project-registry.ts — do not edit.
 *
 * Every registered app's folder, named as a Tailwind source, so the classes an
 * app uses are generated even where git ignores the app (scripts/app-sources.ts
 * says why). Imported by src/app/globals.css.
 */
${lines.join("\n")}${lines.length > 0 ? "\n" : ""}`;
}

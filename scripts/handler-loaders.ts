/**
 * The text of the five generated handler maps: one explicit `import()` per MCP
 * tool, search handler, sync, job and service of every registered app, one
 * file per kind.
 *
 * WHY EXPLICIT. The platform used to load each of these with a template
 * import, `import(\`@apps/${slug}/mcp/${name}\`)` and the like. Turbopack turns
 * that into a context of the files it matches on disk, and whether the context
 * is refreshed when an app gains a file under `next dev` depends on what gets
 * recompiled: the gateway's was not, and a new app's API routes were a 404
 * until a restart (./route-loaders.ts). A generated file of literal imports is
 * rewritten by `npm run registry`, Next recompiles it, and the new handler is
 * in the graph whatever else recompiles. Loading through the map also tells a
 * handler missing from it apart from one that throws at load
 * (src/lib/apps/module-map.ts).
 *
 * WHY ONE FILE PER KIND. Each caller imports only its own kind's map, so its
 * module graph holds what the template's context held and no more: the MCP
 * route does not pull in every job, nor the scheduler every MCP tool, nor the
 * search endpoint either of them.
 *
 * Built from the names in the manifests the scan accepted, each already
 * checked to have a handler on disk, so each map holds exactly the handlers
 * the registry vouches for: a rejected app gets no loaders, as it gets no
 * registry entry.
 */

import { handlerLoaderKey, type HandlerKind } from "../src/lib/apps/handler-modules";

export interface HandlerLoaderApp {
  slug: string;
  mcp?: readonly { name: string }[];
  search?: readonly { name: string }[];
  sync?: readonly { name: string }[];
  schedules?: readonly { name: string }[];
  provides?: readonly { name: string }[];
}

interface HandlerMap {
  /** The generated file, under src/generated/. */
  file: string;
  /** The map's export, which the consumer imports by name. */
  exportName: string;
  /** The map's single consumer, named in the header. */
  consumer: string;
  /** What the map holds, for the header. */
  what: string;
  /** The declared names of this kind, from a registered manifest. */
  names: (app: HandlerLoaderApp) => readonly { name: string }[] | undefined;
}

export const HANDLER_MAPS: Record<HandlerKind, HandlerMap> = {
  mcp: {
    file: "app-mcp-tool-loaders.ts",
    exportName: "mcpToolLoaders",
    consumer: "src/lib/mcp/tools.ts",
    what: "MCP tools",
    names: (app) => app.mcp,
  },
  search: {
    file: "app-search-loaders.ts",
    exportName: "searchLoaders",
    consumer: "src/lib/search/broker.ts",
    what: "search handlers",
    names: (app) => app.search,
  },
  sync: {
    file: "app-sync-loaders.ts",
    exportName: "syncLoaders",
    consumer: "src/lib/apps/scheduler.ts",
    what: "declared syncs",
    names: (app) => app.sync,
  },
  jobs: {
    file: "app-job-loaders.ts",
    exportName: "jobLoaders",
    consumer: "src/lib/apps/scheduler.ts",
    what: "scheduled jobs",
    names: (app) => app.schedules,
  },
  services: {
    file: "app-service-loaders.ts",
    exportName: "serviceLoaders",
    consumer: "src/lib/apps/services.ts",
    what: "provided services",
    names: (app) => app.provides,
  },
};

export const HANDLER_KINDS = Object.keys(HANDLER_MAPS) as HandlerKind[];

export function handlerLoadersSource(kind: HandlerKind, apps: readonly HandlerLoaderApp[]): string {
  const map = HANDLER_MAPS[kind];
  const entries = apps.flatMap((app) =>
    (map.names(app) ?? []).map(({ name }) => {
      const key = handlerLoaderKey(app.slug, kind, name);
      return `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`@apps/${key}`)}),`;
    }),
  );

  return `// AUTO-GENERATED by scripts/generate-project-registry.ts — do not edit
//
// SERVER ONLY. Every registered app's ${map.what}
// (apps/<slug>/${kind}/<name>.ts), one explicit import each, so one added while
// \`next dev\` runs is in the module graph as soon as \`npm run registry\`
// rewrites this file (scripts/handler-loaders.ts says why this is not a
// template import). A handler may reach the database or a connector, so this
// map must never enter the client graph. Its single consumer is
// ${map.consumer}.

export const ${map.exportName}: Record<string, () => Promise<Record<string, unknown>>> = {
${entries.join("\n")}
};
`;
}
